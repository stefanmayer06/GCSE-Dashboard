// Renders the Circuit React graphics to static SVG strings for the public
// pages in selector/ (which ship without React). Output: selector/art.js,
// which fills every <span data-art="name"></span> placeholder at load.
// Re-run after changing any graphic in clients/shared/circuit/.
import { build } from 'esbuild';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
// Build next to the project so bare imports (react, react-dom) resolve
// from website/node_modules; packages stay external (no bundling of CJS).
const dir = path.join(root, 'scripts/art/.build');
mkdirSync(dir, { recursive: true });
const outfile = path.join(dir, 'art.mjs');
await build({
  entryPoints: [path.join(root, 'scripts/art/entry.jsx')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  jsx: 'automatic',
  packages: 'external',
  outfile,
  logLevel: 'error',
});
const { ART } = await import(pathToFileURL(outfile).href);
rmSync(dir, { recursive: true, force: true });

const banner = `// GENERATED by scripts/export-art.mjs — do not edit by hand.
// Static Circuit graphics for the dependency-free public pages. Each
// <span data-art="name"></span> is replaced with the matching inline SVG,
// so colours follow the page's CSS variables and the light/dark theme.
`;
const body = `(() => {
  const ART = ${JSON.stringify(ART)};
  for (const slot of document.querySelectorAll('[data-art]')) {
    const markup = ART[slot.getAttribute('data-art')];
    if (markup) slot.innerHTML = markup;
  }
})();
`;
writeFileSync(path.join(root, 'selector/art.js'), banner + body);
console.log(`Wrote selector/art.js with ${Object.keys(ART).length} graphics (${Math.round((banner + body).length / 1024)} KB).`);

