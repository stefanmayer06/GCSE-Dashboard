const tokens = readFileSync(path.join(root, 'clients/shared/circuit/tokens.css'), 'utf8');
const base = readFileSync(path.join(root, 'clients/shared/circuit/base.css'), 'utf8');
const start = base.indexOf('/* @public:start');
const end = base.indexOf('/* @public:end */');
if (start < 0 || end < 0) throw new Error('base.css is missing the @public markers');
const publicCss = `/* GENERATED by scripts/export-art.mjs — do not edit by hand.
   Circuit tokens + graphics for the public pages (selector/). Edit
   clients/shared/circuit/tokens.css or base.css, then npm run art:export. */
${FONT_FACES}
${tokens}
${base.slice(start, end)}`;
writeFileSync(path.join(root, 'selector/circuit-public.css'), publicCss);
console.log(`Wrote selector/circuit-public.css (${Math.round(publicCss.length / 1024)} KB).`);
